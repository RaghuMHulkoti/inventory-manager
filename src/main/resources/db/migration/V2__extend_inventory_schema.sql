-- V2: Extend inventory schema to support full TDD specification
-- Adds: safety_stock/reorder_point to inventory, idempotency_key/version to reservations,
--       extended ledger fields, and inventory_outbox table.

-- ========================================================================
-- 1. Extend inventory table
-- ========================================================================
ALTER TABLE inventory ADD (
    safety_stock       NUMBER(10) DEFAULT 0 NOT NULL,
    reorder_point      NUMBER(10) DEFAULT 0 NOT NULL,
    last_restocked_at  TIMESTAMP
);

-- ========================================================================
-- 2. Extend stock_reservations table
-- ========================================================================
ALTER TABLE stock_reservations ADD (
    idempotency_key VARCHAR2(80),
    version         NUMBER(19) DEFAULT 0 NOT NULL
);

-- Back-fill idempotency_key for any existing rows (dev/test convenience)
UPDATE stock_reservations SET idempotency_key = RAWTOHEX(id) WHERE idempotency_key IS NULL;
ALTER TABLE stock_reservations MODIFY (idempotency_key NOT NULL);
ALTER TABLE stock_reservations
    ADD CONSTRAINT uq_reservation_idempotency_key UNIQUE (idempotency_key);

-- ========================================================================
-- 3. Extend inventory_ledger table
-- ========================================================================
ALTER TABLE inventory_ledger ADD (
    reservation_id  RAW(16),
    reference_type  VARCHAR2(30),
    actor           VARCHAR2(80)
);

-- ========================================================================
-- 4. New table: inventory_outbox (Transactional Outbox pattern)
-- ========================================================================
CREATE TABLE inventory_outbox (
    id           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aggregate_id RAW(16)         NOT NULL,
    event_type   VARCHAR2(60)    NOT NULL,
    payload      VARCHAR2(32767) NOT NULL,  -- JSON text
    status       VARCHAR2(20)    DEFAULT 'PENDING' NOT NULL,
    created_at   TIMESTAMP       DEFAULT CURRENT_TIMESTAMP NOT NULL,
    sent_at      TIMESTAMP
);
CREATE INDEX idx_inv_outbox_pending ON inventory_outbox (status, created_at);

-- ========================================================================
-- 5. Indexes for reservations (TDD §9.4)
-- ========================================================================
CREATE INDEX idx_resv_order      ON stock_reservations (order_id);
CREATE INDEX idx_resv_status_exp ON stock_reservations (status, expires_at);
CREATE INDEX idx_resv_inv        ON stock_reservations (inventory_id, status);

-- ========================================================================
-- 6. Low-stock index (TDD §9.4) — function-based, Oracle has no partial indexes
-- ========================================================================
CREATE INDEX idx_inv_supplier_product ON inventory (supplier_product_id);
CREATE INDEX idx_inv_low_stock ON inventory ((quantity_on_hand - quantity_reserved - safety_stock));
